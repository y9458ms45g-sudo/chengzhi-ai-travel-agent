def query_scenic(name: str) -> str:
    """
    查询景点基础信息。
    入参：景点名称
    返回：开放时间、门票、地址、注意事项
    """
    # 模糊匹配：名称互相包含；优先精确匹配，再取 key 最长者（最具体优先），
    # 避免"故宫"先于"沈阳故宫"命中北京。
    name = (name or "").strip()
    exact = SCENIC_DATA.get(name)
    if exact:
        key = name
        info = exact
        return (
            f"【{key}】（{info['city']}）\n"
            f"开放时间：{info['open']}\n"
            f"门票：{info['ticket']}\n"
            f"地址：{info['address']}\n"
            f"提示：{info['note']}\n"
            f"（票价/开放时间可能随季节调整，建议出发前再核实官方信息）"
        )
    candidates = [(k, v) for k, v in SCENIC_DATA.items() if k in name or name in k]
    if candidates:
        candidates.sort(key=lambda kv: len(kv[0]), reverse=True)
        key, info = candidates[0]
        return (
            f"【{key}】（{info['city']}）\n"
            f"开放时间：{info['open']}\n"
            f"门票：{info['ticket']}\n"
            f"地址：{info['address']}\n"
            f"提示：{info['note']}\n"
            f"（票价/开放时间可能随季节调整，建议出发前再核实官方信息）"
        )
    # 没找到：按城市列出覆盖范围，帮 LLM 收敛
    from collections import defaultdict
    by_city = defaultdict(list)
    for key, info in SCENIC_DATA.items():
        by_city[info["city"]].append(key)
    lines = [f"未找到「{name}」。当前 scenic 工具覆盖以下城市及景点："]
    for city, spots in by_city.items():
        lines.append(f"- {city}：{'、'.join(spots)}")
    lines.append("如用户问的景点不在列表中，可改用 web_search 联网查询最新信息。")
    return "\n".join(lines)
