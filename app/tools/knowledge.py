_cache = {}


def _load_city_file(city: str) -> str:
    """加载某个城市的知识库文件"""
    if city in _cache:
        return _cache[city]
    # 尝试匹配文件名
    candidates = [
        os.path.join(KNOWLEDGE_DIR, f"{city}文旅知识库.md"),
        os.path.join(KNOWLEDGE_DIR, f"{city}.md"),
        os.path.join(KNOWLEDGE_DIR, f"{city}知识库.md"),
    ]
    for fpath in candidates:
        if os.path.exists(fpath):
            with open(fpath, "r", encoding="utf-8") as f:
                content = f.read()
            _cache[city] = content
            return content
    _cache[city] = ""
    return ""


def _detect_city(query: str) -> list:
    """从query中检测涉及的城市"""
    matched = []
    for city, keywords in CITY_KEYWORDS.items():
        for kw in keywords:
            if kw in query:
                matched.append(city)
                break
    return matched


def search_knowledge(query: str, n_results: int = 3) -> str:
    """
    检索文旅知识库：
    - 智能识别query涉及的城市
    - 只加载相关城市的知识库
    - 没识别到就加载全部
    """
    cities = _detect_city(query)

    if not cities:
        # 兜底：加载全部
        files = glob.glob(os.path.join(KNOWLEDGE_DIR, "*.md"))
        if not files:
            return "[知识库为空] 请在 data/knowledge/ 目录下放置 .md 文件。"
        parts = []
        for fpath in files:
            with open(fpath, "r", encoding="utf-8") as f:
                parts.append(f.read())
        return f"以下是文旅知识库（全部），请根据问题'{query}'提取相关信息：\n\n" + "\n\n---\n\n".join(parts)

    # 按城市加载
    parts = []
    for city in cities:
        content = _load_city_file(city)
        if content:
            parts.append(f"=== {city}文旅知识库 ===\n{content}")
        else:
            parts.append(f"=== {city}文旅知识库 ===\n[暂无{city}的结构化知识库，建议联网搜索补充]")

    return (
        f"以下是与用户问题'{query}'相关的文旅知识库，请基于这些信息回答：\n\n"
        + "\n\n---\n\n".join(parts)
    )
